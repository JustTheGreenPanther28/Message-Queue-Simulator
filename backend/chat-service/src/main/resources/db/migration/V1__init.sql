-- Initial schema for chat-service (database chat_db).


CREATE TABLE conversation_members (
    id bigint NOT NULL,
    conversation_id bigint NOT NULL,
    joined_at timestamp(6) with time zone NOT NULL,
    user_id bigint NOT NULL
);

ALTER TABLE conversation_members ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME conversation_members_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE conversations (
    id bigint NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    created_by bigint NOT NULL,
    creation_key character varying(64),
    direct_key character varying(41),
    last_activity_at timestamp(6) with time zone NOT NULL,
    last_message_id bigint,
    last_seq bigint NOT NULL,
    name character varying(64),
    type character varying(10) NOT NULL,
    CONSTRAINT conversations_type_check CHECK (((type)::text = ANY ((ARRAY['DIRECT'::character varying, 'GROUP'::character varying])::text[])))
);

ALTER TABLE conversations ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME conversations_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE message_receipts (
    id bigint NOT NULL,
    conversation_id bigint NOT NULL,
    delivered_at timestamp(6) with time zone,
    message_id bigint NOT NULL,
    read_at timestamp(6) with time zone,
    user_id bigint NOT NULL
);

ALTER TABLE message_receipts ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME message_receipts_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE messages (
    id bigint NOT NULL,
    client_message_id character varying(64) NOT NULL,
    content character varying(4000),
    conversation_id bigint NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    image_url character varying(200),
    sender_id bigint NOT NULL,
    seq bigint NOT NULL,
    status_level integer NOT NULL,
    type character varying(10) NOT NULL,
    CONSTRAINT messages_type_check CHECK (((type)::text = ANY ((ARRAY['TEXT'::character varying, 'IMAGE'::character varying])::text[])))
);

ALTER TABLE messages ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME messages_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE outbox_events (
    id bigint NOT NULL,
    attempts integer NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    event_id character varying(64) NOT NULL,
    exchange character varying(100) NOT NULL,
    last_error character varying(500),
    next_attempt_at timestamp(6) with time zone NOT NULL,
    payload text NOT NULL,
    published_at timestamp(6) with time zone,
    routing_key character varying(100) NOT NULL
);

ALTER TABLE outbox_events ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME outbox_events_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE processed_events (
    id character varying(120) NOT NULL,
    processed_at timestamp(6) with time zone NOT NULL
);

CREATE TABLE user_profiles (
    id bigint NOT NULL,
    avatar_url character varying(200),
    display_name character varying(40) NOT NULL,
    source_version bigint NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    username character varying(32) NOT NULL
);

