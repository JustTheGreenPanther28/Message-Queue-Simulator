-- 1. Images live in object storage: store keys, not URLs (old local-disk files are not migrated).
ALTER TABLE user_profiles RENAME COLUMN avatar_url TO avatar_key;
UPDATE user_profiles SET avatar_key = NULL;
ALTER TABLE messages RENAME COLUMN image_url TO image_key;
UPDATE messages SET image_key = NULL;

-- 2. Message requests / group invites. Existing members count as accepted.
ALTER TABLE conversation_members
    ADD COLUMN status     varchar(10) NOT NULL DEFAULT 'ACCEPTED',
    ADD COLUMN hidden     boolean     NOT NULL DEFAULT false,
    ADD COLUMN invited_by bigint;
ALTER TABLE conversation_members
    ADD CONSTRAINT conversation_members_status_check CHECK (status IN ('ACCEPTED', 'PENDING', 'REJECTED'));

-- 3. Silent blocking: a receipt for a message the recipient will never see.
ALTER TABLE message_receipts ADD COLUMN suppressed boolean NOT NULL DEFAULT false;

CREATE TABLE user_blocks (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id bigint                   NOT NULL,
    blocked_id bigint                   NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_block_pair UNIQUE (blocker_id, blocked_id)
);
CREATE INDEX idx_block_blocked ON user_blocks (blocked_id);
