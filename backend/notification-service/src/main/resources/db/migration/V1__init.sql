-- Initial schema for notification-service (database notification_db).


CREATE TABLE notifications (
    id bigint NOT NULL,
    body character varying(300) NOT NULL,
    conversation_id bigint,
    created_at timestamp(6) with time zone NOT NULL,
    image_url character varying(200),
    is_read boolean NOT NULL,
    source_key character varying(80) NOT NULL,
    title character varying(100) NOT NULL,
    type character varying(20) NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT notifications_type_check CHECK (((type)::text = ANY ((ARRAY['NEW_MESSAGE'::character varying, 'ADDED_TO_GROUP'::character varying])::text[])))
);

ALTER TABLE notifications ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME notifications_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE processed_events (
    id character varying(120) NOT NULL,
    processed_at timestamp(6) with time zone NOT NULL
);

ALTER TABLE ONLY notifications
    ADD CONSTRAINT notifications_pkey PRIMARY KEY (id);

ALTER TABLE ONLY processed_events
    ADD CONSTRAINT processed_events_pkey PRIMARY KEY (id);

ALTER TABLE ONLY notifications
    ADD CONSTRAINT uk_notification_user_source UNIQUE (user_id, source_key);

CREATE INDEX idx_notification_user ON notifications USING btree (user_id, id);
